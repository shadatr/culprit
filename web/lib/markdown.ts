// Client-side Markdown rendering of a report, for "Copy as Markdown". Mirrors
// the intent of internal/report: every hypothesis keeps its evidence IDs.

import type { Incident, Report } from "./api";
import { between, compact, pct, stampUTC, statusLabel } from "./format";

/** Escapes characters that would break a GFM table cell. */
export function cell(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

function ids(list: string[]): string {
  return list.length ? list.map((id) => `\`${id}\``).join(", ") : "none";
}

export function renderReportMarkdown(report: Report, incident?: Incident): string {
  const out: string[] = [];
  const title = incident?.title || "Incident";
  out.push(`# ${title}`, "");

  const meta: string[] = [];
  if (incident?.service) meta.push(`**Service:** ${incident.service}`);
  if (incident?.started_at) meta.push(`**Started:** ${stampUTC(incident.started_at)}`);
  meta.push(`**Status:** ${statusLabel(report.status)}`);
  if (incident?.id || report.incident_id) meta.push(`**Investigation:** \`${incident?.id || report.incident_id}\``);
  out.push(meta.join("  \n"), "");

  out.push("## Summary", "", report.summary.trim() || "_No summary._", "");

  out.push("## Hypotheses", "");
  if (!report.hypotheses.length) out.push("_No hypotheses._", "");
  report.hypotheses.forEach((h, i) => {
    out.push(`### ${i + 1}. ${h.title} (${pct(h.confidence)})`, "");
    const facts: string[] = [];
    if (h.service) facts.push(`- **Service:** ${h.service}`);
    if (h.category) facts.push(`- **Category:** ${h.category}`);
    if (h.change_id) facts.push(`- **Suspected change:** \`${h.change_id}\``);
    facts.push(`- **Evidence:** ${ids(h.evidence_ids)}`);
    out.push(...facts, "");
    if (h.explanation.trim()) out.push(h.explanation.trim(), "");
    if (h.next_steps.length) {
      out.push("**Next steps**", "");
      for (const s of h.next_steps) out.push(`- [ ] ${s}`);
      out.push("");
    }
  });

  if (report.timeline.length) {
    out.push("## Timeline", "", "| Time (UTC) | Event | Evidence |", "| --- | --- | --- |");
    for (const t of report.timeline) {
      out.push(`| ${cell(stampUTC(t.t))} | ${cell(t.text)} | ${t.evidence_ids.length ? cell(t.evidence_ids.join(", ")) : ""} |`);
    }
    out.push("");
  }

  if (report.evidence.length) {
    out.push("## Evidence", "");
    for (const e of report.evidence) {
      out.push(`- **${e.id}** \`${e.kind || "evidence"}\`${e.tool ? ` via \`${e.tool}\`` : ""}: ${e.summary.replace(/\r?\n/g, " ").trim()}`);
    }
    out.push("");
  }

  const u = report.usage;
  const usage = [
    report.model ? `model ${report.model}` : "",
    `${u.steps} steps`,
    `${u.tool_calls} tool calls`,
    `${compact(u.prompt_tokens + u.completion_tokens)} tokens (${compact(u.prompt_tokens)} in / ${compact(u.completion_tokens)} out)`,
    `took ${between(report.started_at, report.finished_at)}`,
  ].filter(Boolean);
  out.push("---", "", `_Generated by Culprit: ${usage.join(", ")}._`, "");

  return out.join("\n");
}
